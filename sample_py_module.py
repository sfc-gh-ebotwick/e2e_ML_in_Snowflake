def add_numbers(a, b):
  """
  This function adds two numbers.

  Args:
    a: The first number.
    b: The second number.

  Returns:
    The sum of a and b.
  """
  return a + b

def multiply_numbers(a, b):
  """
  This function multiplies two numbers.

  Args:
    a: The first number.
    b: The second number.

  Returns:
    The product of a and b.
  """
  return a * b

